#!/usr/bin/env python3
"""Generates the resource tables of the |BF> papers directly from the reference transpiler,
so the published numbers cannot drift from the implementation.

Usage:  python tools/gen_paper_tables.py          (writes papers/generated/*.tex)
        python tools/gen_paper_tables.py --check  (exit 1 if the committed tables are stale)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src"))
from braketfuck import resource_report  # noqa: E402

PROGRAMS = [
    ("6-Qubit Full", "shor_15_full.bfk", 6),
    ("6-Qubit Full, opt.", "shor_15_full_opt.bfk", 6),
    ("5-Qubit Recycled", "shor_15_recycled.bfk", 5),
    ("5-Qubit Recycled, opt.", "shor_15_recycled_opt.bfk", 5),
]
ORDER = ["ccx", "cx", "ch", "cz", "ctrl @ sdg", "ctrl @ s", "ctrl @ tdg", "ctrl @ t"]


def _fmt_counts(counts):
    parts = [f"{counts[k]} \\texttt{{{k}}}" for k in ORDER if counts.get(k)]
    extra = sorted(k for k in counts if k not in ORDER and k.startswith("ctrl"))
    parts += [f"{counts[k]} \\texttt{{{k}}}" for k in extra]
    return ", ".join(parts) if parts else "--"


def build_shor_table() -> str:
    reports = []
    for label, fname, n in PROGRAMS:
        with open(os.path.join(ROOT, "examples", fname), encoding="utf-8") as f:
            code = f.read()
        reports.append((label, resource_report(code, n, optimize=False), resource_report(code, n, optimize=True),
                        resource_report(code, n, optimize=True, lnn=True)))
    cols = len(reports)
    lines = [
        "% AUTO-GENERATED by tools/gen_paper_tables.py -- do not edit by hand.",
        "\\begin{tabular}{@{}l" + "c" * cols + "@{}}",
        "\\toprule",
        "Metric & " + " & ".join(f"\\texttt{{|BF>}} ({lab})" for lab, *_ in reports) + " \\\\",
        "\\midrule",
        "Tape Register Width ($N$) & " + " & ".join(str(r["qubits"]) for _, r, *_ in reports) + " \\\\",
        "Source Instruction Tokens & " + " & ".join(str(r["tokens"]) for _, r, *_ in reports) + " \\\\",
        "Native \\texttt{\\^{}} tokens & " + " & ".join(str(r["native_cnot_tokens"]) for _, r, *_ in reports) + " \\\\",
        "Multi-qubit gates, per-token lowering & " + " & ".join(_fmt_counts(r["gate_counts"]) for _, r, *_ in reports) + " \\\\",
        "CNOT-equivalents, per-token lowering & " + " & ".join(str(r["cnot_equivalents"]) for _, r, *_ in reports) + " \\\\",
        "Multi-qubit gates, conjugation-aware lowering & " + " & ".join(_fmt_counts(o["gate_counts"]) for _, _, o, *_ in reports) + " \\\\",
        "CNOT-equivalents, conjugation-aware lowering & " + " & ".join(f"\\textbf{{{o['cnot_equivalents']}}}" for _, _, o, *_ in reports) + " \\\\",
        "Circuit depth (ASAP), conjugation-aware & " + " & ".join(str(o["depth"]) for _, _, o, *_ in reports) + " \\\\",
        "Max.\\ interaction distance (all-to-all lowering) & " + " & ".join(str(o["max_interaction_distance"]) for _, _, o, *_ in reports) + " \\\\",
        "\\midrule",
        "\\multicolumn{" + str(cols + 1) + "}{@{}l}{\\emph{Open linear chain (LNN): exact 1-/2-qubit decomposition + SWAP routing}} \\\\",
        "Routing SWAPs inserted & " + " & ".join(str(l["swaps"]) for *_, l in reports) + " \\\\",
        "CNOT-equivalents incl.\\ SWAPs (SWAP $= 3$) & " + " & ".join(f"\\textbf{{{l['cnot_equivalents']}}}" for *_, l in reports) + " \\\\",
        "Circuit depth (ASAP), LNN & " + " & ".join(str(l["depth"]) for *_, l in reports) + " \\\\",
        "Max.\\ interaction distance, LNN & " + " & ".join(str(l["max_interaction_distance"]) for *_, l in reports) + " \\\\",
        "Measurements incl.\\ loop tests / resets & " + " & ".join(f"{o['measurements']} / {o['resets']}" for _, _, o, *_ in reports) + " \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    out_dir = os.path.join(ROOT, "papers", "generated")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "shor_resources.tex")
    content = build_shor_table()
    if "--check" in sys.argv:
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current != content:
            print(f"STALE: {path} does not match the transpiler output; rerun tools/gen_paper_tables.py")
            return 1
        print("Paper tables are up to date.")
        return 0
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
